// Функция получения описания эмодзи
function getEmojiDescription(emoji) {
    return emojiDescriptions[emoji] || 'Эмодзи';
}
// Загрузка недавних эмодзи из localStorage
function loadRecentEmojis() {
    try {
        const recent = localStorage.getItem('recentEmojis');
        return recent ? JSON.parse(recent) : [];
    } catch (e) {
        console.error('Ошибка загрузки недавних эмодзи:', e);
        return [];
    }
}

// Сохранение недавних эмодзи
function saveRecentEmoji(emoji) {
    try {
        let recent = loadRecentEmojis();
        // Убираем дубликаты и оставляем только уникальные
        recent = [emoji, ...recent.filter(e => e !== emoji)].slice(0, 30);
        localStorage.setItem('recentEmojis', JSON.stringify(recent));
        emojiLibrary.recent = recent;
    } catch (e) {
        console.error('Ошибка сохранения эмодзи:', e);
    }
}

