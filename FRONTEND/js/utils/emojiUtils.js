// ============================================================
//  НЕДАВНИЕ ЭМОДЗИ
// ============================================================

function loadRecentEmojis() {
    try {
        const recent = localStorage.getItem('recentEmojis');
        return recent ? JSON.parse(recent) : [];
    } catch (e) {
        console.error('Ошибка загрузки недавних эмодзи:', e);
        return [];
    }
}

function saveRecentEmoji(emoji) {
    try {
        let recent = loadRecentEmojis();
        recent = [emoji, ...recent.filter(e => e !== emoji)].slice(0, 20);
        localStorage.setItem('recentEmojis', JSON.stringify(recent));
        emojiLibrary.recent = recent;
    } catch (e) {
        console.error('Ошибка сохранения эмодзи:', e);
    }
}

// ============================================================
//  ПУБЛИЧНОЕ API
// ============================================================

function getEmojisByCategory(category) {
    if (category === 'recent') {
        return loadRecentEmojis();
    }
    return emojiLibrary[category] || [];
}

function getEmojiDescription(emoji) {
    return emojiDescriptions[emoji] || 'Эмодзи';
}

/**
 * Рендерит сетку эмодзи в контейнере.
 */
function renderEmojiPanel(container, category = 'smileys') {
    if (!container) return;

    const emojis = getEmojisByCategory(category);
    container.innerHTML = '';

    if (emojis.length === 0) {
        const empty = document.createElement('div');
        empty.className = 'emoji-empty';
        empty.textContent = category === 'recent' ? 'Нет недавних эмодзи' : 'Нет эмодзи';
        container.appendChild(empty);
        return;
    }

    const fragment = document.createDocumentFragment();

    emojis.forEach(emoji => {
        const item = document.createElement('button');
        item.type = 'button';
        item.className = 'emoji-item';
        item.textContent = emoji;
        item.dataset.emoji = emoji;

        const description = getEmojiDescription(emoji);
        item.title = description;
        item.setAttribute('aria-label', description);

        item.addEventListener('click', () => {
            const field = document.getElementById('message-field');
            if (!field) return;

            const start = field.selectionStart;
            const end = field.selectionEnd;
            const value = field.value;

            field.value = value.substring(0, start) + emoji + value.substring(end);
            field.selectionStart = field.selectionEnd = start + emoji.length;
            field.focus();

            saveRecentEmoji(emoji);
        });

        fragment.appendChild(item);
    });

    container.appendChild(fragment);
}

